//Operadores relacionales

let a = 5;
let b = 6;

console.log(a);
console.log(b);

//Igualdad
c = a == b;
console.log(c);

console.log('a==b ==>', a == b);
console.log(`${a}==${b} ==> ${a == b}`);

//Igualdad Exacto
console.log(`${a}===${b} ==> ${a === b}`);

//Diferente
c = a != b;
console.log(c);
console.log(`${a}!=${b} ==> ${a != b}`);

//Diferente exacto
c = a !== b;
console.log(c);
console.log(`${a}!==${b} ==> ${a !== b}`);

//Mayor que
c = a >= b;
console.log(c);
console.log(`${a} >= ${b} ==> ${a >= b}`);

//Menor que
c = a <= b;
console.log(c);
console.log(`${a}<=${b} ==> ${a <= b}`);

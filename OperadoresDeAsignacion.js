//Operadores de asignacion

//Para asignar un valor a una variable se utiliza el operador de asignacion (=)

let miNumero = 5;
console.log(miNumero);

miNumero = 10;
console.log(miNumero);

//Operador +=

miNumero += 5;
console.log(miNumero);

//Operador -=

miNumero -= 2;
console.log(miNumero);

//Operador *=

miNumero *= 4;
console.log(miNumero);

//Operaodr /=
miNumero /= 3;
console.log(miNumero);

//Operador %=

miNumero %= 2;
console.log(miNumero);

//potencia
potencia = Math.pow(2, 3);
console.log(potencia);

potencia2 = 2 ** 3;
console.log(potencia2);

//Operaodor **=
miNumero **= 6;
